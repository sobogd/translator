// Regenerates content/index.ts from content/chrome/<locale>.json and
// content/pairs/<locale>/<slug>.json. Run after adding or removing content:
//   node scripts/gen-content-index.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const chromeDir = path.join(root, "content", "chrome");
const pairsDir = path.join(root, "content", "pairs");

const chromeLocales = fs.existsSync(chromeDir)
  ? fs.readdirSync(chromeDir).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort()
  : [];

const pairFiles = [];
if (fs.existsSync(pairsDir)) {
  for (const loc of fs.readdirSync(pairsDir).sort()) {
    const dir = path.join(pairsDir, loc);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (f.endsWith(".json")) pairFiles.push({ loc, slug: f.replace(/\.json$/, "") });
    }
  }
}

const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));

let out = `// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit by hand.
// Static imports (not fs reads) so Next bundles every content JSON without
// output-file-tracing surprises on the standalone prod build.
import type { TranslatorTexts, FeatureContent } from "@/app/_landing/types";
import chromeEn from "@/app/(en)/texts.json";
import chromeRu from "@/app/ru/texts.json";
`;
for (const loc of chromeLocales) {
  out += `import chrome_${ident(loc)} from "./chrome/${loc}.json";\n`;
}
for (const { loc, slug } of pairFiles) {
  out += `import pair_${ident(loc)}_${ident(slug)} from "./pairs/${loc}/${slug}.json";\n`;
}

out += `
// Chrome (header/footer/translator widget + home copy) per locale. en/ru live
// with their static routes; generated locales live in content/chrome/.
export const CHROME: Record<string, TranslatorTexts> = {
  en: chromeEn as TranslatorTexts,
  ru: chromeRu as TranslatorTexts,
`;
for (const loc of chromeLocales) {
  out += `  ${JSON.stringify(loc)}: chrome_${ident(loc)} as unknown as TranslatorTexts,\n`;
}
out += `};

// Pair-page content keyed by \`\${locale}/\${slug}\`.
export const PAIR_CONTENT: Record<string, FeatureContent> = {
`;
for (const { loc, slug } of pairFiles) {
  out += `  ${JSON.stringify(`${loc}/${slug}`)}: pair_${ident(loc)}_${ident(slug)} as unknown as FeatureContent,\n`;
}
out += `};

// Locales whose chrome (and therefore home page) actually exists — the
// rollout gate for static params, sitemap, hreflang and the locale switcher.
export const READY_LOCALES: string[] = ${JSON.stringify(["en", "ru", ...chromeLocales.filter((l) => l !== "en" && l !== "ru")])};
`;

fs.writeFileSync(path.join(root, "content", "index.ts"), out);
console.log(`content/index.ts: ${chromeLocales.length} chrome locales, ${pairFiles.length} pair pages`);
